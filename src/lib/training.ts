export interface LrConfig {
  learning_rate: number;
  warmup_iters: number;
  lr_decay_iters: number;
  min_lr: number;
}

// A direct port of get_lr() in nanoGPT's train.py.
export const getLr = (it: number, c: LrConfig) => {
  if (it < c.warmup_iters) {
    return (c.learning_rate * (it + 1)) / (c.warmup_iters + 1);
  }
  if (it > c.lr_decay_iters) return c.min_lr;
  const ratio = (it - c.warmup_iters) / (c.lr_decay_iters - c.warmup_iters);
  const coeff = 0.5 * (1 + Math.cos(Math.PI * ratio));
  return c.min_lr + coeff * (c.learning_rate - c.min_lr);
};

